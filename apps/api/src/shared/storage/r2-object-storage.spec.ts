import { describe, expect, it } from "vitest";
import { signRequest } from "./r2-object-storage";

describe("signRequest (AWS Signature V4, la que usa Cloudflare R2)", () => {
  // Ejemplo oficial "GET Object" de la documentacion de S3 (sig-v4-header-based-auth): mismas credenciales de
  // ejemplo, misma fecha y el resultado publicado alli.
  it("reproduce la firma del ejemplo oficial de S3", () => {
    const headers = signRequest({
      method: "GET",
      host: "examplebucket.s3.amazonaws.com",
      path: "/test.txt",
      headers: { Range: "bytes=0-9" },
      payloadHash: "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
      accessKeyId: "AKIAIOSFODNN7EXAMPLE",
      secretAccessKey: "wJalrXUtnFEMI/K7MDENG/bPxRfiCYEXAMPLEKEY",
      region: "us-east-1",
      service: "s3",
      amzDate: "20130524T000000Z",
    });

    expect(headers.authorization).toBe(
      "AWS4-HMAC-SHA256 Credential=AKIAIOSFODNN7EXAMPLE/20130524/us-east-1/s3/aws4_request, " +
        "SignedHeaders=host;range;x-amz-content-sha256;x-amz-date, " +
        "Signature=f0e8bdb87c964420e857bd35b5d6ed310bd44f0170aba48dd91039c6036bdb41"
    );
  });
});
